#!/usr/bin/env python3
"""Generate the stock-board configuration from the pinned Cornix layout."""
import argparse
import hashlib
import json
from pathlib import Path
from default_keymap import REFERENCE, REFERENCE_SHA, rmk_action

ROOT = Path(__file__).resolve().parents[1]
BOARD = ROOT / 'source/corex-rmk-pair/right'


def generate():
    raw = REFERENCE.read_bytes()
    assert hashlib.sha256(raw).hexdigest() == REFERENCE_SHA
    stock = json.loads(raw)
    # CoreX uses the RIGHT as central. Preserve every stock physical key and
    # all ten layers; only the halves' matrix/encoder indices are exchanged.
    layers = [layer[4:] + layer[:4] for layer in stock['layout']]
    names = ['通常', '数字・記号', '接続先', '接続先2', '補助'] + [f'予備{i}' for i in range(1, 6)]
    config = '''# Generated by tools/stock_cornix.py. Stock Cornix RIGHT central.
[keyboard]
name = "CoreX Cornix"
product_name = "Cornix CoreX"
vendor_id = 0x4c4b
product_id = 0x4643
manufacturer = "CoreX"
chip = "nrf52840"
[rmk]
split_central_sleep_timeout_seconds = 300
[layout]
rows = 8
cols = 7
map = """
'''
    config += '\n'.join(' '.join(f'({r},{c})' for c in range(7)) for r in range(8)) + '\n"""\n[keymap]\nlayers = 10\n'
    for index, layer in enumerate(layers):
        config += f'[[keymap.layer]]\nname = "{names[index]}"\nkeys = """\n'
        config += '\n'.join(' '.join(rmk_action('KC_NO' if key == -1 else key) for key in row) for row in layer)
        config += '\n"""\nencoders = ' + json.dumps([[rmk_action(cw), rmk_action(ccw)] for ccw, cw in reversed(stock['encoder_layout'][index])]) + '\n'
    # Reuse the current BLE/host/event policy, not the replacement PCB's pins
    # or virtual pointing settings. WS2812 owns P0.24 power / P0.13 data.
    common = (BOARD / 'keyboard-raytac.toml').read_text().split('[ble]\n', 1)[1].split('[[behavior.auto_mouse_layer]]', 1)[0]
    common = common.replace('start_addr = 0xB0000', 'start_addr = 0xC0000').replace('unlock_keys = [[0,5],[0,0]]', 'unlock_keys = [[0,0],[0,5]]').replace('hold_timeout = "200ms"', 'hold_timeout = "250ms"')
    config += '[ble]\n' + common + '''
[event.keyboard]
subs = 4
[event.connection_status_change]
subs = 8
[event.battery_status]
subs = 4
[event.peripheral_connected]
subs = 2
[event.central_connected]
subs = 2
[event.peripheral_battery]
subs = 4
[event.sleep_state]
subs = 4
[split]
connection = "ble"
[split.central]
battery_adc_pin = "P0_05"
adc_divider_measured = 2000
adc_divider_total = 2806
rows = 4
cols = 7
row_offset = 0
col_offset = 0
[split.central.matrix]
row_pins = ["P1_09", "P0_28", "P0_03", "P1_10"]
col_pins = ["P0_30", "P0_31", "P0_29", "P0_02", "P1_13", "P0_10", "P0_09"]
row2col = false
[[split.central.input_device.encoder]]
pin_a = "P1_04"
pin_b = "P1_06"
internal_pullup = true
phase = "resolution"
resolution = 4
reverse = false
debounce_ms = 5
'''
    peripheral = (BOARD / 'keyboard-raytac.toml').read_text().split('[[split.peripheral]]', 1)[1].split('# Raytac A14 ENC1', 1)[0]
    config += '[[split.peripheral]]' + peripheral
    definition = (ROOT / 'keymaps/reference/cornix-v1.12-definition.json').read_bytes()
    assert hashlib.sha256(definition).hexdigest() == '5e080d8c7aa33f95f4fbaa93110bf24cdb5af631781719efeed462690526627c', 'Manufacturer definition changed'
    vial = json.loads(definition)
    vial.update(name='CoreX Cornix', vendorId='0x4C4B', productId='0x4643')
    vial['customKeycodes'] = json.loads((BOARD / 'vial-raytac.json').read_text())['customKeycodes'][:8]
    vial['layouts'].pop('labels', None)
    for row in vial['layouts']['keymap']:
        for i, value in enumerate(row):
            if not isinstance(value, str):
                continue
            labels = value.split('\n')
            r, c = map(int, labels[0].split(','))
            if '\ne' in value:
                labels[0] = f'{1-r},{c}'
            else:
                labels[0] = f'{(r+4)%8},{c}'
            # Remove the manufacturer's firmware-version layout option.
            if len(labels) > 4:
                labels[4] = ''
            row[i] = '\n'.join(labels)
    return config, vial


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    config, vial = generate()
    for name, text in [('keyboard-stock.toml', config), ('vial-stock.json', json.dumps(vial, ensure_ascii=False, indent=2)+'\n')]:
        path = BOARD / name
        if args.check:
            assert path.read_text() == text, f'Stale generated file: {name}'
        else:
            path.write_text(text)
    print('PASS stock Cornix: ten layers, original physical keys and both encoders')


if __name__ == '__main__':
    main()
