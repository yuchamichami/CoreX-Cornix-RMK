#!/usr/bin/env python3
"""Generate the board's gesture contract from the same source as Studio."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
BOARD = ROOT / 'source/corex-rmk-pair/right'
config = json.loads((BOARD / 'gestures.json').read_text())
settings = [*config['directions'], config['sensitivity']]
cells = [(item['layer'], item['row'], item['col']) for item in settings]
# Only reuse the three already-established virtual cells, on spare layers.
# No physical switch, layer-0 pointer preset or new storage capacity is involved.
assert len(set(cells)) == 5
assert all(layer in (5, 6) and row in (0, 1, 2) and col == 6 for layer, row, col in cells)
output = '// Generated by tools/generate_gestures.py; edit gestures.json.\n'
output += 'pub const CONFIG: rmk::input_device::pointing::gesture::Config = rmk::input_device::pointing::gesture::Config {\n'
output += f'    trigger_user: {config["triggerUser"]},\n'
output += f'    cells: [{", ".join(str(cell) for cell in cells)}],\n'
output += f'    sensitivity_users: {config["sensitivity"]["users"]},\n'
output += f'    thresholds: {config["sensitivity"]["thresholds"]},\n'
output += '};\n'
destination = BOARD / 'src/gesture_config.rs'
parser = argparse.ArgumentParser()
parser.add_argument('--check', action='store_true')
if parser.parse_args().check:
    if not destination.exists() or destination.read_text() != output:
        raise SystemExit('Regenerate gesture_config.rs with tools/generate_gestures.py')
else:
    destination.write_text(output)
